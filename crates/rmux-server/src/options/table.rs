/// `OPTIONS_TABLE_HOOK` and its pane/window variants: a command array
/// hook with an empty default and an empty separator.
const fn hook(name: &'static [u8], scope: OptionsScope, text: &'static [u8]) -> OptionsTableEntry {
    OptionsTableEntry {
        name,
        kind: OptionsTableType::Command,
        scope,
        flags: OptionsTableFlags(OptionsTableFlags::ARRAY.0 | OptionsTableFlags::HOOK.0),
        minimum: 0,
        maximum: 0,
        choices: None,
        default_str: Some(b""),
        default_num: 0,
        default_arr: None,
        separator: Some(b""),
        pattern: None,
        text,
        unit: None,
    }
}

