#[repr(i32)]
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum KeyCodeType {
    Unicode = 0,
    User = 1,
    Function = 2,
    Mousemove = 3,
    Mousedown = 4,
    Mouseup = 5,
    Mousedrag = 6,
    Mousedragend = 7,
    Wheeldown = 8,
    Wheelup = 9,
    Secondclick = 10,
    Doubleclick = 11,
    Tripleclick = 12,
    Notype = 13,
}
impl TryFrom<i32> for KeyCodeType {
    type Error = i32;
    fn try_from(value: i32) -> Result<Self, i32> {
        match value {
            0 => Ok(Self::Unicode),
            1 => Ok(Self::User),
            2 => Ok(Self::Function),
            3 => Ok(Self::Mousemove),
            4 => Ok(Self::Mousedown),
            5 => Ok(Self::Mouseup),
            6 => Ok(Self::Mousedrag),
            7 => Ok(Self::Mousedragend),
            8 => Ok(Self::Wheeldown),
            9 => Ok(Self::Wheelup),
            10 => Ok(Self::Secondclick),
            11 => Ok(Self::Doubleclick),
            12 => Ok(Self::Tripleclick),
            13 => Ok(Self::Notype),
            _ => Err(value),
        }
    }
}

