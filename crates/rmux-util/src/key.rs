#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct KeyCode(pub u64);
impl KeyCode {
    pub const NUSER: u32 = 1000;
    pub const CLICK_TIMEOUT: u32 = 300;
    pub const MOUSE_LOCATION_SHIFT: u32 = 0;
    pub const MOUSE_BUTTON_SHIFT: u32 = 8;
    pub const fn mouse(kind: KeyCodeType, button: u32, location: MouseLocation) -> Self {
        Self(((kind as u64) << 32) | ((button as u64) << 8) | location as u64)
    }
    pub const fn is_type(self, kind: KeyCodeType) -> bool {
        self.0 & KeyMasks::TYPE == (kind as u64) << 32
    }
    pub const fn is_unicode(self) -> bool {
        self.is_type(KeyCodeType::Unicode) && self.0 & KeyMasks::KEY > 0x7f
    }
    pub const fn is_user(self) -> bool {
        self.is_type(KeyCodeType::User)
    }
    pub const fn is_special(self) -> bool {
        self.is_type(KeyCodeType::Function)
    }
    pub const fn is_mouse(self) -> bool {
        let tag = self.0 & KeyMasks::TYPE;
        self.0 & KeyMasks::KEY == SpecialKey::MOUSE
            || (tag >= (KeyCodeType::Mousemove as u64) << 32
                && tag <= (KeyCodeType::Tripleclick as u64) << 32)
    }
    pub const fn is_paste(self) -> bool {
        self.is_special()
            && (self.0 & KeyMasks::KEY == SpecialKey::PASTE_START
                || self.0 & KeyMasks::KEY == SpecialKey::PASTE_END)
    }
    pub const fn user(index: u32) -> Option<Self> {
        if index < Self::NUSER {
            Some(Self(SpecialKey::USER + index as u64))
        } else {
            None
        }
    }
}
impl MouseButtonBits {
    pub const fn buttons(self) -> u32 {
        self.0 & Self::BUTTONS.0
    }
    pub const fn is_release(self) -> bool {
        self.buttons() == 3
    }
    pub const fn is_wheel(self) -> bool {
        self.buttons() == 64 || self.buttons() == 65
    }
    pub const fn is_drag(self) -> bool {
        self.0 & Self::DRAG.0 != 0
    }
}
